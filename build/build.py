def build_content(raster: bool) -> None:
    for word in BRAND_WORDS:
        rays = BRANDS[word]
        for scheme in ("dark", "light"):
            for kind, title, meta, body in CONTENT[word]:
                slug = kind.replace(" ", "-")
                p = write(
                    f"content/{word}-{slug}-{scheme}.svg",
                    SF.content_card(
                        1200, 675, word, rays, scheme,
                        kind=kind, title=title, meta=meta, body=body,
                    ),
                )
                if raster:
                    png(p, width=1200)


def build_favicons(raster: bool) -> None:
    if not raster:
        return
    for word in BRAND_WORDS:
        src = ROOT / f"logo/svg/{word}-mark.svg"
        tile = ROOT / f"logo/svg/{word}-mark-tile-dark.svg"
        for size in (16, 32, 48, 180, 192, 512):
            base = src if size <= 48 else tile
            subprocess.run(
                ["rsvg-convert", str(base), "-w", str(size), "-h", str(size),
                 "-o", str(ROOT / "icons" / f"{word}-icon-{size}.png")],
                check=True,
            )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--svg", action="store_true", help="skip the raster pass")
    args = ap.parse_args()
    raster = not args.svg
    if raster and not shutil.which("rsvg-convert"):
        sys.exit("rsvg-convert not found -- `brew install librsvg`, or pass --svg")

    (ROOT / "logo/png").mkdir(parents=True, exist_ok=True)
    (ROOT / "icons").mkdir(parents=True, exist_ok=True)

    build_tokens()
    print("tokens        ok")
    build_logos(raster)
    print("logos         ok")
    build_spinners()
    print("spinners      ok")
    build_wallpapers(raster)
    print("wallpapers    ok")
    build_social(raster)
    print("social        ok")
    build_ads(raster)
    print("ads           ok")
    build_content(raster)
    print("content       ok")
    build_favicons(raster)
    print("icons         ok")

    n = sum(1 for _ in ROOT.rglob("*") if _.is_file() and _.suffix in {".svg", ".png"})
    print(f"\n{n} files under {ROOT}")


if __name__ == "__main__":
    main()

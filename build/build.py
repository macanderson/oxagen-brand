def build_favicons(raster: bool) -> None:
    """16 to 48 from the favicon mark on nothing; 180 and up from the dark tile."""
    for b in BRAND_WORDS:
        fav = write(f"logo/svg/{b}-favicon.svg", favicon_svg(b))
        if not raster:
            continue
        tile = ROOT / f"logo/svg/{b}-icon-tile-dark.svg"
        for size in (16, 32, 48, 180, 192, 512):
            src = fav if size <= 48 else tile
            png(src, width=size, height=size, out=ROOT / "icons" / f"{b}-icon-{size}.png")


def check() -> int:
    problems = C.verify() + G.verify()
    for p in problems:
        print("problem:", p)
    if not problems:
        m = G.wordmark("oxagen")
        print(f"check: oxagen reproduces the kit wordmark ({m['width']:g} x {m['height']:g}, em {G.EM:.2f})")
        print(f"check: gold {C.GOLD} is the reference {C.REFERENCE_GOLD} lifted by {C.GOLD_LIFT}")
        print("check: every text token clears AA on its ground")
    return 1 if problems else 0


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--svg", action="store_true", help="skip the raster pass")
    ap.add_argument("--check", action="store_true", help="verify, write nothing")
    args = ap.parse_args()
    if args.check:
        sys.exit(check())
    raster = not args.svg
    if raster and not shutil.which("rsvg-convert"):
        sys.exit("rsvg-convert not found -- `brew install librsvg`, or pass --svg")
    if check():
        sys.exit("the kit does not verify; not writing")

    for d in GENERATED:
        shutil.rmtree(ROOT / d, ignore_errors=True)
    (ROOT / "logo/png").mkdir(parents=True, exist_ok=True)
    (ROOT / "icons").mkdir(parents=True, exist_ok=True)

    build_tokens()
    print("tokens        ok")
    build_logos(raster)
    print("logos         ok")
    build_favicons(raster)
    print("icons         ok")
    build_spinners()
    print("spinners      ok")
    build_wallpapers(raster)
    print("wallpapers    ok")
    build_social(raster)
    print("social        ok")
    build_ads(raster)
    print("ads           ok")
    build_content(raster)
    print("content       ok")

    n = sum(1 for _ in ROOT.rglob("*") if _.is_file() and _.suffix in {".svg", ".png"} and ".venv" not in _.parts)
    print(f"\n{n} files under {ROOT}")


if __name__ == "__main__":
    main()

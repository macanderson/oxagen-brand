"""Write the whole kit. Nothing in this repository is drawn by hand.

    python3 build/build.py            # write every asset
    python3 build/build.py --svg      # skip the PNG raster pass (fast)

Rasterising needs `rsvg-convert` (`brew install librsvg`). Every PNG here is a
render of the SVG beside it, so a colour can only be changed in one place --
`build/color.py` -- and everything downstream follows on the next run.
"""


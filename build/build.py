def build_logos(raster: bool) -> list[Path]:
    made = []
    for word in BRAND_WORDS:
        rays = BRANDS[word]
        variants = {
            "dark": wordmark_svg(word, rays, uid=f"{word}-d"),
            "light": wordmark_svg(word, rays, letters=INK_TEXT, uid=f"{word}-l"),
            "adaptive": wordmark_svg(word, rays, adaptive=True, uid=f"{word}-a"),
            "mono": wordmark_svg(word, rays, mono="currentColor"),
            "mono-white": wordmark_svg(word, rays, mono=PAPER_TEXT),
            "mono-black": wordmark_svg(word, rays, mono=INK_TEXT),
        }
        for name, svg in variants.items():
            made.append(write(f"logo/svg/{word}-wordmark-{name}.svg", svg))
        for name in ("dark", "light"):
            bg = C.INK if name == "dark" else C.PAPER
            made.append(
                write(
                    f"logo/svg/{word}-wordmark-{name}-onground.svg",
                    wordmark_svg(
                        word,
                        rays,
                        letters=PAPER_TEXT if name == "dark" else INK_TEXT,
                        background=bg,
                        uid=f"{word}-{name}-bg",
                    ),
                )
            )
        # the star alone
        made.append(write(f"logo/svg/{word}-mark.svg", star_only_svg(rays, uid=f"{word}-m")))
        made.append(
            write(
                f"logo/svg/{word}-mark-mono-white.svg",
                star_only_svg(rays, mono=PAPER_TEXT, uid=f"{word}-mw"),
            )
        )
        made.append(
            write(
                f"logo/svg/{word}-mark-mono-black.svg",
                star_only_svg(rays, mono=INK_TEXT, uid=f"{word}-mb"),
            )
        )
        for label, bg, rad in (("tile-dark", C.INK, 20), ("tile-light", C.PAPER, 20)):
            made.append(
                write(
                    f"logo/svg/{word}-mark-{label}.svg",
                    star_only_svg(rays, background=bg, radius=rad, uid=f"{word}-{label}"),
                )
            )
    if raster:
        for p in made:
            if "wordmark" in p.name:
                for w in (512, 1024, 2048):
                    subprocess.run(
                        ["rsvg-convert", str(p), "-w", str(w), "-o",
                         str(ROOT / "logo/png" / f"{p.stem}-{w}w.png")],
                        check=True,
                    )
            else:
                for w in (256, 512, 1024):
                    subprocess.run(
                        ["rsvg-convert", str(p), "-w", str(w), "-o",
                         str(ROOT / "logo/png" / f"{p.stem}-{w}.png")],
                        check=True,
                    )
    return made


def build_spinners() -> None:
    for word in BRAND_WORDS:
        rays = BRANDS[word]
        write(f"spinners/{word}-spinner.svg", spinner_svg(rays, uid=f"{word}-sp"))
        write(
            f"spinners/{word}-spinner-tile-dark.svg",
            spinner_svg(rays, background=C.INK, uid=f"{word}-spd"),
        )
        write(
            f"spinners/{word}-spinner-wordmark.svg",
            spinner_wordmark_svg(word, rays, uid=f"{word}-spw"),
        )


DESKTOP = [(3840, 2160, "4k"), (5120, 2880, "5k"), (6016, 3384, "6k")]
PHONE = [(1290, 2796, "iphone-pro"), (1179, 2556, "iphone"), (1320, 2868, "iphone-pro-max")]


def build_wallpapers(raster: bool) -> None:
    for word in BRAND_WORDS:
        rays = BRANDS[word]
        for scheme in ("dark", "light"):
            for style in ("aurora", "quiet"):
                for w, h, tag in DESKTOP:
                    p = write(
                        f"wallpapers/desktop/{word}-desktop-{tag}-{style}-{scheme}.svg",
                        SF.wallpaper_desktop(w, h, rays, scheme, style),
                    )
                    if raster:
                        png(p, width=w)
                for w, h, tag in PHONE:
                    p = write(
                        f"wallpapers/phone/{word}-{tag}-{style}-{scheme}.svg",
                        SF.wallpaper_phone(w, h, rays, scheme, style),
                    )
                    if raster:
                        png(p, width=w)


def build_social(raster: bool) -> None:
    for word in BRAND_WORDS:
        rays = BRANDS[word]
        tag, dom = TAGLINES[word], DOMAINS[word]
        for scheme in ("dark", "light"):
            jobs = [
                (f"social/{word}-avatar-1024-{scheme}.svg", SF.avatar(rays, 1024, scheme), 1024),
                (
                    f"social/{word}-x-banner-{scheme}.svg",
                    SF.banner(1500, 500, word, rays, scheme, tagline=tag),
                    1500,
                ),
                (
                    f"social/{word}-linkedin-banner-{scheme}.svg",
                    SF.banner(1584, 396, word, rays, scheme, tagline=tag),
                    1584,
                ),
                (
                    f"social/{word}-youtube-banner-{scheme}.svg",
                    SF.banner(2560, 1440, word, rays, scheme, tagline=tag, safe_h=423),
                    2560,
                ),
                (
                    f"social/{word}-og-1200x630-{scheme}.svg",
                    SF.og_card(1200, 630, word, rays, scheme, tagline=tag),
                    1200,
                ),
            ]
            for rel, svg, w in jobs:
                p = write(rel, svg)
                if raster:
                    png(p, width=w)


